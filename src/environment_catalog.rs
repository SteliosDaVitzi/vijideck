//! Developer-tool metadata shared by discovery and presentation. Names remain stable cache keys.
pub struct Spec {
    pub name: &'static str,
    pub exe: &'static str,
    pub arg: &'static str,
    pub category: Category,
    pub group: &'static str,
    pub primary: bool,
    pub release_url: Option<&'static str>,
}
#[derive(Clone, Copy)]
pub enum Category {
    Runtime,
    PackageManager,
    Other,
}
impl Category {
    pub fn label(self) -> &'static str {
        match self {
            Self::Runtime => "Languages & runtimes",
            Self::PackageManager => "Package managers",
            Self::Other => "Other tools",
        }
    }
}
pub fn spec(name: &str) -> Option<&'static Spec> {
    TOOLS.iter().find(|spec| spec.name == name)
}
